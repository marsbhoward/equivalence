"""Writes the approved eight-direction head art (Tools/hair/views5, Tools/faces) into the game:
Assets/Scripts/Art/BodyLook.Views5Art.cs. Re-run after any approved grid changes.

    /usr/bin/python3 Tools/views5/gen.py
"""
import os, re, glob
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HAIR = os.path.join(ROOT, 'Tools/hair/views5'); FACES = os.path.join(ROOT, 'Tools/faces')
OUT = os.path.join(ROOT, 'Assets/Scripts/Art/BodyLook.Views5Art.cs')

def parse_hair(path):
    parts, tops, cur = {}, {}, None
    for l in open(path).read().split('\n'):
        l = l.strip()
        if not l or l[0] in '#@': continue
        m = re.match(r'^(side|q|turned|back)\.(cap|mane)(?: (\d+))?$', l)
        if m:
            cur = f'{m.group(1)}.{m.group(2)}'; parts[cur] = []
            if m.group(3): tops[cur] = int(m.group(3))
            continue
        if cur: parts[cur].append(l)
    return parts, tops

def parse_face(path):
    out, key, cur = {}, None, None
    for l in open(path).read().split('\n'):
        l = l.strip()
        if not l or l[0] == '#': continue
        if l[0] == '@': key = l[1:]; out[key] = {}; cur = None; continue
        m = re.match(r'^(side|q|sideL) (\d+)$', l)
        if m: cur = m.group(1); out[key][cur] = (int(m.group(2)), []); continue
        if cur: out[key][cur][1].append(l)
    return out

def arr(rows, ind):
    return 'new[]\n' + ind + '{\n' + ''.join(f'{ind}    "{r}",\n' for r in rows) + ind + '}'

def view(parts, tops, v, ind):
    cap = parts.get(f'{v}.cap'); mane = parts.get(f'{v}.mane')
    if cap is None: return None
    s = 'new HairView(' + arr(cap, ind + '    ')
    if mane: s += ',\n' + ind + '    ' + arr(mane, ind + '    ') + f',\n{ind}    {tops.get(f"{v}.mane", 32)}'
    return s + ')'

lines = ['// GENERATED by Tools/views5/gen.py from the approved grids in Tools/hair/views5 and Tools/faces - do not edit by hand.',
         '// The eight-direction head (RIG.md "Eight directions"): each hairstyle\'s SIDE (profile) and BACK 3/4 views, the',
         '// front 3/4 and back views the user changed, the views facing LEFT for the styles that are not the same both',
         '// sides (stored as their mirror image facing right), and the brows, marks and beards for side and back 3/4.',
         'using System.Collections.Generic;', '', 'namespace Convergence.Art', '{', '    public static partial class BodyLook', '    {']
dicts = {'ProfileArt': 'side', 'BackQuarterArt': 'q', 'TurnedArt5': 'turned', 'BackArt5': 'back'}
hair = {}
for p in sorted(glob.glob(os.path.join(HAIR, '*.txt'))):
    k = os.path.basename(p)[:-4]; hair[k] = parse_hair(p)
for dname, v in dicts.items():
    for left in (False, True):
        name = dname + ('Left' if left else '')
        lines.append(f'        static Dictionary<string, HairView> {name} => _{name[0].lower()+name[1:]} ??= new Dictionary<string, HairView>')
        lines.append('        {')
        for k, (parts, tops) in hair.items():
            if k.endswith('~') != left: continue
            s = view(parts, tops, v, '            ')
            if s: lines.append(f'            ["{k.rstrip("~")}"] = {s},')
        lines.append('        };')
        lines.append(f'        static Dictionary<string, HairView> _{name[0].lower()+name[1:]};')
        lines.append('')
for kind in ('brow', 'mark', 'beard'):
    f = parse_face(os.path.join(FACES, f'{kind}.txt'))
    for part, suffix in (('side', 'Profile'), ('sideL', 'ProfileLeft'), ('q', 'BackQuarter')):
        name = f'{kind.capitalize()}{suffix}'
        lines.append(f'        /// <summary>{kind} grids, composed texels (32 wide, BeardRows tall), placed from their first row.</summary>')
        lines.append(f'        static Dictionary<string, (int at, string[] rows)> {name} => _{name[0].lower()+name[1:]} ??= new Dictionary<string, (int, string[])>')
        lines.append('        {')
        for k, d in f.items():
            if part in d and d[part][1]:
                at, rows = d[part]
                lines.append(f'            ["{k}"] = ({at}, ' + arr(rows, '            ') + '),')
        lines.append('        };')
        lines.append(f'        static Dictionary<string, (int at, string[] rows)> _{name[0].lower()+name[1:]};')
        lines.append('')
lines += ['    }', '}', '']
open(OUT, 'w').write('\n'.join(lines))
print(OUT, sum(1 for _ in open(OUT)), 'lines')
